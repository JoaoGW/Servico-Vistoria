// Helper function to get crypto logo
export const getCryptoLogo = (symbol: string, size: number = 40) => {
  const logoMap: Record<string, React.FC<CryptoLogoProps>> = {
    BTC: BitcoinLogo,
    ETH: EthereumLogo,
    USDT: TetherLogo,
    BNB: BNBLogo,
    SOL: SolanaLogo,
    XRP: RippleLogo,
    ADA: CardanoLogo,
    DOGE: DogecoinLogo,
    AVAX: AvalancheLogo,
    MATIC: PolygonLogo,
  };

  const LogoComponent = logoMap[symbol];
  return LogoComponent ? <LogoComponent size={size} /> : null;
};
